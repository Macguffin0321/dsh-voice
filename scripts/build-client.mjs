#!/usr/bin/env node
/**
 * Build `lib/client.js` — the browser bundle DSH's client module system loads.
 *
 * The client half is written as ordinary ES modules under `client/` so its pure
 * parts can be unit-tested with plain `node`. The shipped artifact must be a
 * single classic script that registers itself with `window.__ModuleLoader__`,
 * so this script:
 *
 * 1. inlines every `./x.js` import in dependency order,
 * 2. strips the `import` / `export` statements (the whole graph becomes one
 *    function scope),
 * 3. wraps the result in the loader call DSH expects, with `react`,
 *    `react-dom/client` and `react/jsx-runtime` resolved through the loader's
 *    own `require` (they are part of the platform seed table).
 *
 * The output is checked with `node --check` before it is written, so a syntax
 * error can never reach a running harness.
 *
 * @module dsh-voice/scripts/build-client
 */

import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const clientDir = join(root, 'client')

/** Entry module, then its transitive dependencies in load order. */
const ENTRY = 'index.js'

/** The loader id the browser registers this bundle under. */
const BUNDLE_ID = 'dsh-voice'

/** Modules the loader's platform seed table answers synchronously. */
const PLATFORM_MODULES = new Set(['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime', 'react/jsx-dev-runtime'])

/** Read one client module's source. */
function read(relative) {
  return readFileSync(join(clientDir, relative), 'utf8')
}

/**
 * Resolve the module graph depth-first so a dependency always precedes its
 * importer, and every module appears exactly once.
 */
function order(entry) {
  const seen = new Set()
  const out = []

  const visit = (file) => {
    if (seen.has(file)) return
    seen.add(file)
    const source = read(file)
    for (const match of source.matchAll(/^import\s[^'"]*from\s+'(\.[^']+)'/gmu)) {
      visit(match[1].replace(/^\.\//u, ''))
    }
    out.push(file)
  }

  visit(entry)
  return out
}

/**
 * Turn one module into a fragment of the single output scope.
 *
 * Relative imports and exports disappear; platform imports are collected so
 * the wrapper can bind them once from the loader's `require`.
 */
function transform(file) {
  const source = read(file)
  /** @type {Set<string>} */
  const externals = new Set()
  let body = source

  body = body.replace(/^import\s+\{([^}]*)\}\s+from\s+'([^']+)'\s*$/gmu, (whole, names, specifier) => {
    if (specifier.startsWith('.')) return ''
    externals.add(specifier)
    const bindings = names
      .split(',')
      .map((name) => name.trim())
      .filter((name) => name !== '')
      .map((name) => {
        const alias = /^(\S+)\s+as\s+(\S+)$/u.exec(name)
        return alias === null ? name : `${alias[1]}: ${alias[2]}`
      })
      .join(', ')
    return `const { ${bindings} } = require(${JSON.stringify(specifier)})`
  })
  body = body.replace(/^import\s+\*\s+as\s+(\S+)\s+from\s+'([^']+)'\s*$/gmu, (whole, name, specifier) => {
    if (specifier.startsWith('.')) return ''
    externals.add(specifier)
    return `const ${name} = require(${JSON.stringify(specifier)})`
  })
  body = body.replace(/^import\s+'([^']+)'\s*$/gmu, (whole, specifier) => {
    if (specifier.startsWith('.')) return ''
    externals.add(specifier)
    return `require(${JSON.stringify(specifier)})`
  })
  body = body.replace(/^export\s+\{[^}]*\}\s*$/gmu, '')
  body = body.replace(/^export\s+(?=(?:async\s+)?(?:function|class|const|let|var)\b)/gmu, '')
  if (/^\s*(?:import|export)\s/mu.test(body)) {
    throw new Error(`unhandled import/export remains in client/${file}`)
  }
  return { body: body.trim(), externals }
}

/** Build the bundle text. */
function build() {
  const files = order(ENTRY)
  const externals = new Set()
  const parts = []
  for (const file of files) {
    const { body, externals: found } = transform(file)
    for (const specifier of found) externals.add(specifier)
    parts.push(`// ── client/${file} ${'─'.repeat(Math.max(0, 60 - file.length))}\n${body}`)
  }
  const unsupported = [...externals].filter((specifier) => !PLATFORM_MODULES.has(specifier))
  if (unsupported.length > 0) {
    throw new Error(`client bundle may only import platform modules; found: ${unsupported.join(', ')}`)
  }
  const requires = [...externals]
    .map((specifier) => `\t\tconst ${identOf(specifier)} = require(${JSON.stringify(specifier)})`)
    .join('\n')
  const exports = files
    .filter((file) => file === ENTRY)
    .map(() => '')
    .join('')

  return `/**
 * dsh-voice — browser bundle. GENERATED by scripts/build-client.mjs; edit
 * client/*.js and re-run \`node scripts/build-client.mjs\`.
 */
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(BUNDLE_ID)},
\tfactory: (require) => {
\t\tvar module = { exports: {} }
\t\tvar exports = module.exports
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" })
${requires}
${parts.join('\n\n')}

\t\texports.name = name
\t\texports.inject = inject
\t\texports.apply = apply
${exports}\t\treturn module.exports
\t},
})
`
}

/** The local binding name for one platform specifier. */
function identOf(specifier) {
  if (specifier === 'react') return 'react'
  return specifier.replace(/[^A-Za-z0-9]/gu, '_')
}

const output = build()
const target = join(root, 'lib', 'client.js')
mkdirSync(dirname(target), { recursive: true })
const scratch = join(root, 'lib', `.client-${process.pid}.js`)
writeFileSync(scratch, output, 'utf8')
try {
  execFileSync(process.execPath, ['--check', scratch], { stdio: 'pipe' })
} catch (error) {
  rmSync(scratch, { force: true })
  const detail = error.stderr === undefined ? String(error) : error.stderr.toString()
  throw new Error(`generated client bundle is not valid JavaScript:\n${detail}`)
}
rmSync(scratch, { force: true })
writeFileSync(target, output, 'utf8')
const bytes = Buffer.byteLength(output, 'utf8')
process.stdout.write(`dsh-voice: wrote lib/client.js (${String(bytes)} bytes, ${String(order(ENTRY).length)} modules)\n`)
